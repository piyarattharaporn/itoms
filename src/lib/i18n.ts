export function getLanguage(): Language {
  if (typeof window === 'undefined') return 'th'
  return window.localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'th'
}

export function getLocale(): string {
  return getLanguage() === 'en' ? 'en-US' : 'th-TH'
}

export function setLanguage(language: Language): void {
  window.localStorage.setItem(STORAGE_KEY, language)
  document.documentElement.lang = language
  window.dispatchEvent(new CustomEvent('lotus-language-change', { detail: language }))
}

export function t(text: string | null | undefined, params?: TranslationParams): string {
  if (!text) return ''
  const language = getLanguage()
  const catalogValue = catalog[language][text as TranslationKey]
  if (catalogValue) return interpolate(catalogValue, params)
  if (language === 'en') {
    const exact = english[text] ?? englishFeature[text]
    if (exact) return interpolate(exact, params)
    const dynamic: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
      [/^(\d+) \/100 รายการ$/, (match) => `${match[1]} / 100 items`],
      [/^เพิ่ม Asset (.+) แล้ว \((.+)\)$/, (match) => `Added asset ${match[1]} (${match[2]}).`],
      [/^บันทึก Asset (.+) แล้ว$/, (match) => `Saved asset ${match[1]}.`],
      [/^เพิ่ม Asset (.+) แล้ว$/, (match) => `Added asset ${match[1]}.`],
      [/^สร้าง Task (.+) แล้ว$/, (match) => `Created task ${match[1]}.`],
      [/^บันทึกเหตุขัดข้องแล้ว \((.+)\)$/, (match) => `Incident logged (${match[1]}).`],
      [/^บันทึกผลตรวจ CCTV ของ (.+) สำหรับวันนี้แล้ว$/, (match) => `Saved today's CCTV check for ${match[1]}.`],
      [
        /^วันที่ภาพเก่าสุดของ (.+) ไม่ถูกต้องหรืออยู่หลังวันที่ตรวจ$/,
        (match) => `The oldest footage date for ${match[1]} is invalid or later than the check date.`,
      ],
      [/^อัปเดต PM Schedule “(.+)” แล้ว$/, (match) => `Updated PM schedule “${match[1]}”.`],
      [/^สร้าง PM Schedule “(.+)” แล้ว$/, (match) => `Created PM schedule “${match[1]}”.`],
      [/^บันทึก PM แล้ว \(Run (.+)\)$/, (match) => `Saved PM result (run ${match[1]}).`],
      [/^เพิ่มรายการ “(.+)” แล้ว$/, (match) => `Added “${match[1]}”.`],
      [/^เหลือ (\d+) วัน$/, (match) => `${match[1]} days left`],
      [/^หมดอายุแล้ว (\d+) วัน$/, (match) => `Expired ${match[1]} days ago`],
      [/^แก้ไข “(.+)” เป็น “(.+)” แล้ว$/, (match) => `Changed “${match[1]}” to “${match[2]}”.`],
      [/^แก้ไข (.+) แล้ว$/, (match) => `Updated ${match[1]}.`],
      [
        /^NVR (.+) Offline จึงระบุกล้อง Online ไม่ได้$/,
        (match) => `NVR ${match[1]} is offline, so online cameras cannot be entered.`,
      ],
      [/^จำนวนกล้องของ (.+) ไม่ถูกต้อง$/, (match) => `The camera count for ${match[1]} is invalid.`],
      [
        /^จำนวนวันย้อนหลังของ (.+) ต้องอยู่ระหว่าง 0 ถึง 3,650 วัน$/,
        (match) => `The retention period for ${match[1]} must be between 0 and 3,650 days.`,
      ],
      [
        /^หมายเหตุของ (.+) ต้องไม่เกิน 500 ตัวอักษร$/,
        (match) => `The note for ${match[1]} must be 500 characters or fewer.`,
      ],
      [/^รหัส NVR (.+) ซ้ำกัน$/, (match) => `The NVR ID ${match[1]} is duplicated.`],
      [
        /^วันที่ภาพเก่าสุดของ (.+) ไม่ถูกต้องหรืออยู่หลังวันที่ตรวจ$/,
        (match) => `The oldest footage date for ${match[1]} is invalid or later than the check date.`,
      ],
      [/^ไม่สามารถเปลี่ยนสถานะจาก (.+) เป็น (.+)$/, (match) => `Cannot change status from ${match[1]} to ${match[2]}.`],
    ]
    for (const [pattern, translate] of dynamic) {
      const match = text.match(pattern)
      if (match) return interpolate(translate(match), params)
    }
    return text
  }
  return (
    thaiFeature[text] ??
    Object.entries({ ...english, ...englishFeature }).find(([, translated]) => translated === text)?.[0] ??
    text
  )
}

export function tKey(key: TranslationKey, params?: TranslationParams): string {
  return t(key, params)
}
